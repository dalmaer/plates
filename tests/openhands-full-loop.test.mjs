// No Python dependency required for default repo gates. Native evidence uses the explicit replay CLI.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { run } from './helpers/run.mjs';
import { renderTrace, openDemo, acceptLesson, sha, LESSON_TEXT } from '../experiments/openhands/full-loop.mjs';
import { parseLessons } from '../lib/lessons.mjs';

test('two-project loop survives real coordinator SIGKILL, captures once, shares exact lesson and withdraws harmful scope (worker double)', async t => {
  const parent = await mkdtemp(join(tmpdir(), 'acme-openhands-loop-'));
  t.after(() => rm(parent, { recursive: true, force: true }));
  const root = join(parent, 'run');
  const result = run(process.execPath, [resolve('experiments/openhands/full-loop.mjs'), '--output', root, '--fixture-worker'], { timeout: 30000 });
  assert.equal(result.status, 0, result.stderr);
  const summary = JSON.parse(result.stdout), state = JSON.parse(await readFile(join(root, 'trace.json'), 'utf8'));
  assert.equal(summary.backend, 'fixture-only');
  assert.equal(summary.crash.signal, 'SIGKILL');
  assert.equal(summary.crash.code, null);
  assert.equal(summary.operations, 6);
  assert.equal(state.demo.workerLaunches.length, 6);
  assert.equal(new Set(state.demo.workerLaunches.map(l => l.operation)).size, 6);
  const outcomes = state.demo.trace.filter(e => e.kind === 'execution-outcome');
  assert.deepEqual(outcomes.map(o => o.passed), [false, true, false, true, false, true]);
  const recovery = state.runs[state.demo.steps['one-recovery']];
  assert.equal(recovery.learning, 'captured');
  assert.equal(state.lessons['acme-trim-boundaries'].operation, recovery.id);
  assert.equal(state.demo.crash.checkpoint.operation, recovery.id);
  assert.equal(state.demo.trace.find(e => e.kind === 'coordinator-recovered').redispatched, false);
  const lesson = state.lessons['acme-trim-boundaries'];
  assert.equal(lesson.text, LESSON_TEXT);
  assert.deepEqual(lesson.eligible, ['acme-one']);
  assert.equal(lesson.revision, 3);
  assert.ok(state.demo.trace.find(e => e.kind === 'review-denials').decisions.includes('modified proposal bytes denied'));
  assert.deepEqual(lesson.history.map(h => h.reviewer), [2, 2]);
  const applied = state.demo.plans[state.demo.steps['two-applied']];
  assert.equal(applied.lesson.digest, sha(lesson.text));
  assert.equal(applied.lesson.revision, 2);
  assert.equal(state.demo.plans[state.demo.steps['two-harm']].lesson.digest, applied.lesson.digest);
  const rows = parseLessons(await readFile(join(root, 'home/docs/lessons.md'), 'utf8')).rows;
  assert.equal(rows.length, 2, 'one real Plates accepted catalogue row');
  assert.match(rows[1].guard, /Trim boundary whitespace/);
  assert.deepEqual(Object.values(state.runs).map(r => r.account), ['acme-account-1', 'acme-account-1', 'acme-account-2', 'acme-account-2', 'acme-account-2', 'acme-account-2']);
  assert.equal(Object.values(state.messages).filter(m => m.state === 'conflict').length, 6);
  assert.equal(Object.values(state.effects).filter(e => e.name.startsWith('message:')).length, 6, 'coordinator and conflicting messages cannot reach worker');
  assert.equal(summary.pendingLearning, 0);
  assert.equal(summary.usage.two.attempts, 4);
  assert.equal(summary.usage.two.billingVerified, false);
  assert.ok(Object.values(state.runs).every(r => r.terminated));
  const adapter = openDemo(root);
  t.after(() => adapter.close());
  const before = adapter.read();
  await assert.rejects(acceptLesson(adapter, root, 'acme-alice-session', sha(LESSON_TEXT)), /review_authority/);
  await assert.rejects(acceptLesson(adapter, root, 'forged-model-text', sha(LESSON_TEXT)), /authority/);
  await assert.rejects(acceptLesson(adapter, root, 'acme-bob-session', sha(LESSON_TEXT)), /exact revision/);
  assert.deepEqual(adapter.read(), before, 'unauthorized review cannot mutate journal');
  const rerun = run(process.execPath, [resolve('experiments/openhands/full-loop.mjs'), '--output', root, '--fixture-worker']);
  assert.notEqual(rerun.status, 0, 'replay refuses an existing output directory');
  assert.deepEqual(adapter.read(), before);
});

test('read-only trace escapes hostile content; filtering never dispatches actions', () => {
  const html = renderTrace({ demo: { trace: [{ seq: 1, kind: 'human-message', backend: '<img src=x onerror=alert(1)>', text: '</pre><script>fetch("https://evil.test")</script>' }] } });
  assert.ok(html.includes('&lt;script&gt;fetch('));
  assert.ok(!html.includes('<script>fetch('));
  assert.ok(!html.includes('<img src=x'));
  assert.equal((html.match(/<script>/g) ?? []).length, 1);
  assert.match(html, /saved read-only trace/);
});
